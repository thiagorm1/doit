package com.doit.api.studies.domain;

import jakarta.persistence.*;
import java.time.LocalDateTime;

@Entity
@Table(name = "pomodoro_sessions")
public class PomodoroSession {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false)
    private int focusTime; // in minutes

    @Column(nullable = false)
    private int shortBreak; // in minutes

    @Column(nullable = false)
    private int longBreak; // in minutes

    @Column(nullable = false)
    private int cycles;

    @Column(nullable = false)
    private LocalDateTime createdAt;

    public PomodoroSession() {
    }

    public PomodoroSession(int focusTime, int shortBreak, int longBreak, int cycles, LocalDateTime createdAt) {
        this.focusTime = focusTime;
        this.shortBreak = shortBreak;
        this.longBreak = longBreak;
        this.cycles = cycles;
        this.createdAt = createdAt;
    }

    public Long getId() {
        return id;
    }

    public int getFocusTime() {
        return focusTime;
    }

    public int getShortBreak() {
        return shortBreak;
    }

    public int getLongBreak() {
        return longBreak;
    }

    public int getCycles() {
        return cycles;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    // Get total focus time generated by this session (focusTime * cycles)
    public int getTotalFocusTime() {
        return this.focusTime * this.cycles;
    }

    // Get total break time generated by this session (shortBreak * (cycles - 1) + longBreak)
    // Assuming a long break happens after the cycles finish, or at the end.
    public int getTotalBreakTime() {
        int shorts = Math.max(0, this.cycles - 1);
        return (this.shortBreak * shorts) + this.longBreak;
    }
}
